const generateChallan = (rolls, details) => {
    try {
        const doc = new jsPDF();
        doc.setFontSize(22);
        doc.text("KSF NON WOVEN", 105, 20, null, null, "center");
        doc.setFontSize(12);
        doc.text("Shahjahanpur, Uttar Pradesh", 105, 28, null, null, "center");
        doc.text("DISPATCH CHALLAN / GATE PASS", 105, 36, null, null, "center");
        doc.setFontSize(10);
        doc.text(`Date: ${new Date().toLocaleDateString()} ${new Date().toLocaleTimeString()}`, 14, 50);
        doc.text(`Buyer: ${details.buyer}`, 14, 56);
        doc.text(`Vehicle No: ${details.vehicle}`, 14, 62);
        doc.text(`Generated By: ${details.device}`, 14, 68);
        const tableData = rolls.map((r, i) => [i + 1, r.product_id || '-', r.quality || '-', r.color || '-', `${r.width_inches || 0}"`, `${r.gsm || 0}`, `${r.net_weight || 0} kg`]);
        doc.autoTable({ startY: 75, head: [['#', 'Roll ID', 'Quality', 'Color', 'Size', 'GSM', 'Weight']], body: tableData, theme: 'grid', headStyles: { fillColor: [41, 128, 185] } });
        const finalY = (doc.lastAutoTable && doc.lastAutoTable.finalY) ? doc.lastAutoTable.finalY : 150;
        const totalWt = rolls.reduce((sum, r) => sum + Number(r.net_weight || 0), 0);
        doc.setFontSize(12);
        doc.setFont(undefined, 'bold');
        doc.text(`Total Rolls: ${rolls.length}`, 14, finalY + 10);
        doc.text(`Total Weight: ${totalWt.toLocaleString()} kg`, 150, finalY + 10);
        doc.setFont(undefined, 'normal');
        doc.text("Authorized Signatory", 14, finalY + 30);
        doc.text("Receiver's Signature", 150, finalY + 30);
        const cleanName = (details.buyer || 'Unknown').replace(/[^a-z0-9]/gi, '_');
        doc.save(`KSF_GatePass_${cleanName}_${Date.now()}.pdf`);
        return true;
    } catch (err) {
        alert("PDF Error: " + err.message);
        return false;
    }
};

